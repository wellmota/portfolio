// vértices de um subcaminho só com M/L/l/V/v/Z (o parser aceita negativos colados: "47.63-23.81")
export function verts(d: string): Pt[] {
  const out: Pt[] = [];
  let x = 0;
  let y = 0;
  const re = /([MLVvlZ])([^MLVvlZ]*)/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(d))) {
    const c = m[1];
    const n = (m[2].match(/-?\d*\.?\d+(?:e[-+]?\d+)?/g) || []).map(Number);
    if (c === 'M' || c === 'L') for (let i = 0; i < n.length; i += 2) { x = n[i]; y = n[i + 1]; out.push([x, y]); }
    else if (c === 'l') for (let i = 0; i < n.length; i += 2) { x += n[i]; y += n[i + 1]; out.push([x, y]); }
    else if (c === 'V') { y = n[0]; out.push([x, y]); }
    else if (c === 'v') { y += n[0]; out.push([x, y]); }
  }
  return out;
}

// envoltória convexa (monotone chain)
export function hull(pts: Pt[]): Pt[] {
  const p = [...pts].sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  const cr = (o: Pt, a: Pt, b: Pt) => (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);
  const lo: Pt[] = [];
  const up: Pt[] = [];
  for (const q of p) { while (lo.length >= 2 && cr(lo[lo.length - 2], lo[lo.length - 1], q) <= 0) lo.pop(); lo.push(q); }
  for (const q of p.reverse()) { while (up.length >= 2 && cr(up[up.length - 2], up[up.length - 1], q) <= 0) up.pop(); up.push(q); }
  return lo.slice(0, -1).concat(up.slice(0, -1));
}

